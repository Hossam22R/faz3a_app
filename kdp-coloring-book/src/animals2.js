function tentacle(x0, dir, len = 200, w0 = 36, seed = 0) {
  const lp = [], rp = [];
  const N = 9;
  for (let i = 0; i <= N; i++) {
    const t = i / N;
    const cx = x0 + dir * (Math.sin(t * Math.PI * 1.4 + seed) * 22 + t * 55);
    const cy = 30 + t * len;
    const ww = (w0 * (1 - t * 0.72)) / 2;
    lp.push([cx - ww, cy]);
    rp.push([cx + ww, cy]);
  }
  return smooth(lp.concat(rp.reverse()), true, 0.9);
}

