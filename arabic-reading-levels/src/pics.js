// SVG مستقل لصورة: data-fit يجعل السكربت يقصّه على حدود الرسم
function pic(id, cls = 'pic') {
  setMode('line');
  const root = inner => `<g fill="none" stroke="${INK}" stroke-width="7" stroke-linejoin="round" stroke-linecap="round">${inner}</g>`;
  if (ANIMALS[id]) {
    const a = byName(ANIMALS[id]);
    const vb = FIXED_VB[id];
    const body = root(a.main()).replace(/<text[^>]*>[A-Z]+<\/text>/g, '');
    return `<svg class="${cls}" xmlns="http://www.w3.org/2000/svg" ${vb ? `viewBox="${vb}"` : 'data-fit="1" viewBox="0 0 850 1100"'} preserveAspectRatio="xMidYMid meet">${body}</svg>`;
  }
  if (!OBJ[id]) throw new Error('no pic ' + id);
  return `<svg class="${cls}" xmlns="http://www.w3.org/2000/svg" data-fit="1" viewBox="-130 -130 260 260" preserveAspectRatio="xMidYMid meet">${root(OBJ[id]())}</svg>`;
}

